import * as THREE from 'three';

/**
 * Ключевой час суток. zen, hor — небо в зените и у горизонта; sun, sunI — цвет и сила солнца (ночью — луны);
 * hemiS, hemiG, hemiI — рассеянный свет неба, отсвет земли и их сила (от них цвет теней); fog — дымка вдали;
 * wS, wD — вода на мели и на глубине; cloud — облака; stars — звёзды 0…1; glit — блики на воде и сетка света на дне;
 * exp — выдержка.
 */
const COLORS = ['zen', 'hor', 'sun', 'hemiS', 'hemiG', 'fog', 'wS', 'wD', 'cloud'];
const K = (h, zen, hor, sun, sunI, hemiS, hemiG, hemiI, fog, wS, wD, cloud, stars, glit, exp) => {
  const k = { h, zen, hor, sun, sunI, hemiS, hemiG, hemiI, fog, wS, wD, cloud, stars, glit, exp };
  for (const c of COLORS) k[c] = new THREE.Color(k[c]);
  return k;
};
const _hsl = { h: 0, s: 0, l: 0 };
const c01 = (v) => Math.max(0, Math.min(1, v));
/**
 * Тот же набор часов с поправками. Для цвета: [сдвиг тона в долях круга, множитель насыщенности, множитель светлоты];
 * для числа (sunI, hemiI, glit) — множитель. Так из одной палитры получается родственная: мягче, темнее, теплее.
 */
function vary(keys, rule) {
  return keys.map((k) => {
    const o = { ...k };
    for (const c of COLORS) {
      o[c] = k[c].clone();
      const r = rule[c];
      if (!r) continue;
      o[c].getHSL(_hsl, THREE.SRGBColorSpace);
      o[c].setHSL((_hsl.h + (r[0] || 0) + 1) % 1, c01(_hsl.s * (r[1] ?? 1)), c01(_hsl.l * (r[2] ?? 1)), THREE.SRGBColorSpace);
    }
    for (const n of ['sunI', 'hemiI', 'glit']) if (rule[n]) o[n] = k[n] * rule[n];
    return o;
  });
}

