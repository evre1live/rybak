// Один камень на локацию. Скалы, утёсы, валуны, плиты у воды и камень рельефа — разные модели с разными
// текстурами, и рядом они спорили тоном и цветом: жёлто-бурый утёс, светло-серый валун, серая стена склона.
// Здесь всё приводится к одному камню локации: у модели остаётся её рисунок (трещины, пласты, светлое и тёмное),
// а яркость и цвет — общие. Камень рельефа (surface.js, uRockC) берёт тот же цвет.
import { LOC_ID } from './loc/id.js';

// цвет камня локации (sRGB): бухта — тёплый песчаник, озеро — серый гранит, островки — светлый известняк,
// Синий простор — бурый базальт, Водопадная чаша — тёмный мокрый базальт
const HEX = { bay: '#a3998a', lake: '#8f8e89', keys: '#c4bba6', blue: '#706860', cascade: '#6a685e' };
// средняя яркость «каменных» вершин рельефа этой локации (линейный цвет): от неё рельеф отсчитывает светлое и тёмное
const VERT = { bay: 0.2586, lake: 0.2586, keys: 0.3015, blue: 0.1197, cascade: 0.118 };
// Средний цвет текстуры моделей — по площади, линейный (tools/albedo.py)
const ALBEDO = {
  'env-rock1': [0.1774, 0.1864, 0.0935],
  'env-rock2': [0.1553, 0.1676, 0.1416],
  'env-rock3': [0.128, 0.1363, 0.1451],
  'env-cliff1': [0.1875, 0.1674, 0.0885],
  'env-cliff2': [0.157, 0.1595, 0.1007],
  'env-granite': [0.1283, 0.1248, 0.0751],
  'env-coral': [0.4071, 0.3158, 0.1691],
  'env-seastack': [0.1783, 0.1665, 0.1176],
  'env-seacave': [0.1041, 0.1172, 0.0634],
  'env-shore': [0.0653, 0.0526, 0.0374],
  'env-pebbles': [0.1788, 0.1629, 0.1479],
  'env-fallcliff-bay': [0.1949, 0.1756, 0.122],
  'env-fallcliff-lake': [0.0962, 0.1073, 0.0804],
  'env-arch': [0.1947, 0.199, 0.1553]
};
// сколько своего цвета оставить модели: мох и лишайник чуть зеленее камня, но в той же гамме
const SAT = { 'env-pebbles': 0.45 };
const SAT0 = 0.28;
// модели освещены так же, как рельеф, но у них свои тени и блики — чуть светлее, чтобы стояли в тон
const GAIN = 1.08;

const lin = (v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const lum = (c) => 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
const hex = HEX[LOC_ID] || HEX.bay;
const TARGET = [1, 3, 5].map((i) => lin(parseInt(hex.slice(i, i + 2), 16) / 255));
const TL = lum(TARGET);

/** Цвет камня локации (sRGB, '#rrggbb') — для камня рельефа. */
export const STONE_HEX = hex;
/** Средняя яркость «каменных» вершин рельефа (линейная) — рельеф делит на неё, чтобы взять цвет камня с их рисунком. */
export const STONE_VERT = VERT[LOC_ID] || VERT.bay;
/** Есть ли у модели поправка до общего камня. */
export const isStone = (id) => id in ALBEDO;
/**
 * Как нарисовать модель камнем локации: tint — множитель яркости (копиям россыпи), sat — сколько своего цвета
 * оставить, post — цвет камня после обесцвечивания (patchModel). Для чужой модели — null.
 */
export function stoneLook(id) {
  const a = ALBEDO[id];
  if (!a) return null;
  const k = (TL / lum(a)) * GAIN;
  return { tint: { r: k, g: k, b: k }, sat: SAT[id] ?? SAT0, post: TARGET.map((v) => v / TL) };
}
