export const LOC_BY_ID = Object.fromEntries(LOCATIONS.map((l) => [l.id, l]));
export const DEFAULT_LOC = 'bay';
/** Описание локации по id; неизвестный id — бухта. */
export const locOf = (id) => LOC_BY_ID[id] || LOC_BY_ID[DEFAULT_LOC];
/** id локации из чего угодно (сообщение сети, адрес, запись в базе): неизвестное — бухта. */
export const cleanLoc = (id) => (typeof id === 'string' && LOC_BY_ID[id] ? id : DEFAULT_LOC);
/** Может ли рыбак этого уровня сам открыть комнату на локации. */
export const canHost = (id, lvl) => lvl >= locOf(id).level;
